"""Package source with an explicit per-file SHA-256 manifest. Never include live secrets/data."""
from pathlib import Path
import hashlib, json, zipfile

ROOT = Path(__file__).resolve().parents[1]
ALLOWED_DIRS = {'src','android','cloud','docs','history','launchers','patches','tests','tools','vendor','.github','desktop'}
ALLOWED_FILES = {'README.md','CHANGELOG.md','VERSION.txt','package.json','.gitattributes','.gitignore','requirements-docs.txt','requirements-test.txt','SOURCE_PROVENANCE.json','START_HERE.md','LICENSE.txt','RELEASE_SOURCE_SHA256.json','SYNC_TO_GITHUB.cmd'}
SKIP_PARTS = {'node_modules','.git','.gradle','build','__pycache__','artifacts','native-artifacts','data','release','web','.smoke-output'}

def included(path: Path) -> bool:
    relative = path.relative_to(ROOT)
    if relative.parts[0] not in ALLOWED_DIRS and relative.as_posix() not in ALLOWED_FILES:
        return False
    if any(p in SKIP_PARTS for p in relative.parts):
        return False
    if relative.parts[:6] == ('android','app','src','main','assets','www'):
        return False  # Rebuilt via npm run android:assets on the CI runner.
    if path.name in {'config.php','local.properties','.env'} or path.suffix.lower() in {'.pyc','.jks','.keystore','.p12','.pem','.pfx','.key','.b64'}:
        return False
    # QA images/reports are generated by tests and do not belong in the Git source baseline.
    return path.is_file() and not path.is_symlink()

files = [p for p in sorted(ROOT.rglob('*')) if included(p)]
manifest = {p.relative_to(ROOT).as_posix():hashlib.sha256(p.read_bytes()).hexdigest() for p in files}
manifest_bytes = (json.dumps({'version':(ROOT/'VERSION.txt').read_text().splitlines()[0], 'algorithm':'SHA-256', 'files':manifest},indent=2)+'\n').encode()
(ROOT/'MANIFEST_SHA256.json').write_bytes(manifest_bytes)
output = ROOT/'artifacts'/'RetroBooth_v0.9.10_Android_Windows_GitHub_Ready.zip'
output.parent.mkdir(exist_ok=True)
with zipfile.ZipFile(output,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9) as archive:
    for name, data in [(p.relative_to(ROOT).as_posix(),p.read_bytes()) for p in files] + [('MANIFEST_SHA256.json',manifest_bytes)]:
        info=zipfile.ZipInfo(name,(2026,11,27,0,0,0))
        info.compress_type=zipfile.ZIP_DEFLATED;info.create_system=3;info.external_attr=0o100644<<16
        archive.writestr(info,data,compresslevel=9)
print(json.dumps({'file':str(output),'manifest_files':len(files),'bytes':output.stat().st_size,'sha256':hashlib.sha256(output.read_bytes()).hexdigest()},indent=2))
