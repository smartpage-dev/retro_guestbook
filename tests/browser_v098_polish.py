"""v0.9.8 real Chromium QA: guest labels, private-status UI, paper ratios, unicode bitmap, FPS settings.
No physical Android SPP/Hostinger deployment implied.
"""
from pathlib import Path
import os,json,base64
from playwright.sync_api import sync_playwright
R=Path(__file__).resolve().parents[1];Q=R/'qa/v098';Q.mkdir(parents=True,exist_ok=True)
checks=[];errors=[]
def check(name,success):
 if not success:raise AssertionError(name)
 checks.append(name);print('PASS',name,flush=True)
with sync_playwright() as pw:
 browser=pw.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH') or None,headless=True,args=['--no-sandbox'])
 p=browser.new_page(viewport={'width':1280,'height':720},device_scale_factor=1)
 p.on('pageerror',lambda e:errors.append(str(e)))
 p.set_content((R/'dist/RetroBooth_Prototype.html').read_text())
 p.wait_for_function('window.RetroApp?.status.ready')
 check('engineering canvas overlay hidden from guests',p.locator('#pictureFormat').evaluate("e=>getComputedStyle(e).display==='none'"))
 check('large former privacy text hidden by default',p.locator('#privacyNoticeCompact').is_hidden())
 check('guest sees QR ticket status instead', 'QR TICKET' in p.locator('#panelBoundary').inner_text())
 check('guest printer not-ready not called connected',p.locator('#panelBoundary').get_attribute('data-ready')=='false')
 check('native label converter exists',p.evaluate('typeof RetroPrinter.ticketDesign === "function"'))
 detail=p.evaluate("""()=>RetroPrinter.ticketDesign({title:'歡迎蒞臨',receiptCaption:'永結同心 · 留低美好回憶',receiptFooter:'多謝你哋 祝福滿滿',receiptStyle:'premiere'})""")
 check('unicode title caption footer emitted as rasters',all(detail.get(f'ticket{part}RasterHeight',0)>0 for part in ('Title','Caption','Footer')))
 check('unicode text never converted to ASCII question marks',detail['ticketTitle']==detail['ticketCaption']==detail['ticketFooter']=='')
 check('title raster bounded to 384-dot width',len(base64.b64decode(detail['ticketTitleRasterBase64']))==48*detail['ticketTitleRasterHeight'])
 check('UTF8 caption raster bounded to 384-dot width',len(base64.b64decode(detail['ticketCaptionRasterBase64']))==48*detail['ticketCaptionRasterHeight'])
 check('new receipt style retained in native metadata',detail['ticketStyle']=='premiere')
 for key in ['classic','ticket','minimal','premiere','filmstrip','boarding']:
  check('ticket style '+key+' available',p.locator('#receiptStyle option[value="'+key+'"]').count()==1)
 p.evaluate('RetroApp.go("admin")')
 p.locator('.advanced-guest-settings summary').click()
 p.locator('#panelMakerInput').fill('LUCE STUDIO HONG KONG')
 p.locator('#panelProductInput').fill('RETROVISION SPECIAL')
 p.locator('#panelSubtitleInput').fill('WELCOME TO YOUR VIDEO GUESTBOOK CELEBRATION')
 p.locator('#panelChannelInput').fill('08')
 p.locator('#renderMaxFpsInput').select_option('12')
 p.locator('#renderHeightInput').select_option('540')
 p.locator('#guestScreenInfoInput').uncheck()
 p.locator('#settingsForm button[type=submit]').click()
 p.wait_for_function('RetroApp.status.settings.panelProduct === "RETROVISION SPECIAL"')
 p.evaluate('RetroApp.go("booth")')
 check('admin TV maker setting applies to guest console',p.locator('#panelMaker').inner_text()=='LUCE STUDIO HONG KONG')
 check('admin product setting applies to guest console',p.locator('#panelProduct').inner_text()=='RETROVISION SPECIAL')
 check('admin subtitle setting applies to guest console',p.locator('#panelModel').inner_text()=='WELCOME TO YOUR VIDEO GUESTBOOK CELEBRATION')
 check('admin channel applies to guest console',p.locator('#panelChannel').inner_text()=='08')
 check('FPS cap persisted locally',p.evaluate('RetroApp.status.settings.renderMaxFps')=='12')
 check('render height persisted locally',p.evaluate('RetroApp.status.settings.renderHeight')==540)
 check('engineering disclaimer stays hidden after settings',p.locator('#privacyNoticeCompact').is_hidden())
 w=p.locator('#panelModel').bounding_box();panel=p.locator('.control-panel').bounding_box()
 check('long subtitle does not cross panel edge',w['x']>=panel['x']-2 and w['x']+w['width']<=panel['x']+panel['width']+1)
 p.screenshot(path=str(Q/'v098-branding-1280x720.png'))
 p.evaluate('RetroApp.go("admin")')
 p.locator('#ticketOrientation').select_option('landscape')
 p.locator('#receiptStyle').select_option('premiere')
 p.wait_for_function('document.querySelector("#designCanvas").width===624')
 check('landscape ticket preview 624 dots',p.locator('#designCanvas').evaluate('(c)=>c.width===624'))
 check('landscape preview has white paper across full width',p.locator('#designCanvas').evaluate("""c=>{let px=c.getContext('2d').getImageData(610,2,1,1).data;return px[0]>245&&px[1]>245&&px[2]>245&&px[3]===255}"""))
 p.screenshot(path=str(Q/'v098-receipt-admin-1280x720.png'),full_page=True)
 p.locator('#ticketOrientation').select_option('portrait')
 p.wait_for_function('document.querySelector("#designCanvas").width===384')
 check('portrait ticket preview 384 dots',p.locator('#designCanvas').evaluate('(c)=>c.width===384'))
 p.locator('#guestScreenInfoInput').check()
 p.locator('#settingsForm button[type=submit]').click()
 p.wait_for_function('RetroApp.status.settings.guestScreenInfo===true')
 p.evaluate('RetroApp.go("booth")')
 check('privacy note is optional and can be enabled',not p.locator('#privacyNoticeCompact').is_hidden())
 check('no browser errors',not errors)
 guest=(R/'cloud/public_html/guest/index.html').read_text()
 for required in ['下載影片','重新連線','你的私人影片','大屏幕播放同意','刪除影片','播放','Delete recording']:
  check('Chinese/English guest interface '+required,required in guest)
 (Q/'v098-polish-results.json').write_text(json.dumps({'checks':checks,'total':len(checks),'errors':errors,'scope':'Chromium synthetic Android web surface, simulated CPU/media and no real Bluetooth or Hostinger'},indent=2,ensure_ascii=False)+'\n')
 browser.close()
print('TOTAL',len(checks),'PASSED')
