'use strict';
const assert=require('node:assert/strict');
const {Ring,safe}=require('../src/diagnostics.js');
const ring=new Ring(10);
ring.add('camera_failure',{name:'NotReadableError',deviceId:'secret-device',label:'personal microphone',url:'https://booth.example/guest/#owner-secret',error:'Fetch https://booth.example/private?token=abc failed'});
const entry=ring.snapshot()[0];
assert.equal(entry.detail.name,'NotReadableError');
assert.equal(entry.detail.deviceId,'[REDACTED]');
assert.equal(entry.detail.label,'[REDACTED]');
assert.equal(entry.detail.url,'[REDACTED]');
assert(!JSON.stringify(entry).includes('owner-secret'));
assert(!JSON.stringify(entry).includes('token=abc'));
assert.equal(safe({media:{cameraCount:2}}).media.cameraCount,2);
assert.equal(safe({authorization:'Bearer abc'}).authorization,'[REDACTED]');
for(let i=0;i<15;i++)ring.add('event_'+i,{n:i});
assert.equal(ring.snapshot().length,10);
assert.equal(ring.snapshot()[0].name,'event_5');
ring.clear();assert.equal(ring.snapshot().length,0);
console.log('Diagnostic privacy, ring bounds, and clear checks passed.');
