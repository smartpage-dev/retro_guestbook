"""Regression for independent camera/microphone WebView capture. Synthetic A/V only.
Does NOT establish real Android hardware permission or WebRTC audio routing success.
"""
from pathlib import Path
import json, os
from playwright.sync_api import sync_playwright
R=Path(__file__).resolve().parents[1]
fixture=(R/'tests/browser_v05.py').read_text().split("fixture=r'''",1)[1].split("'''",1)[0]
checks=[]
def check(label,ok):
    if not ok:raise AssertionError(label)
    checks.append(label)
    print('PASS',label,flush=True)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH') or None,headless=True,args=['--no-sandbox'])
    ctx=browser.new_context(viewport={'width':390,'height':844},accept_downloads=True)
    page=ctx.new_page();page.set_default_timeout(20000);errors=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    html=(R/'dist/RetroBooth_Prototype.html').read_text().replace('(async function () {',fixture+'\n(async function () {',1)
    page.set_content(html);page.wait_for_function('window.RetroApp?.status.ready');page.evaluate('RetroApp.go("admin")')
    check('camera Apply button',page.locator('#applyCameraOnly').count()==1)
    check('microphone Apply button',page.locator('#applyMicOnly').count()==1)
    check('microphone-only release button',page.locator('#releaseMicOnly').count()==1)
    check('sequential Apply both option retained',page.locator('#applyDevices').count()==1)
    page.evaluate('window.__fx.failMic=true')
    page.locator('#applyCameraOnly').click()
    page.wait_for_function('RetroApp.status.mode==="preview"')
    check('camera-only stays in preview',page.evaluate('RetroApp.status.mode==="preview"'))
    check('camera request does NOT request audio',page.evaluate('__fx.constraints.at(-1).audio===false'))
    check('camera has a live video track',page.evaluate('__fx.streams.at(-1).stream.getVideoTracks().some(t=>t.readyState==="live")'))
    check('video element has real synthetic dimensions',page.evaluate('document.querySelector("#inputVideo").videoWidth>0'))
    page.wait_for_function("document.querySelector('#cameraLabState').textContent.includes('CAMERA-ONLY')")
    check('preview has explicit no-mic label',page.locator('#cameraLabState').inner_text().find('CAMERA-ONLY')>=0)
    page.locator('#effectsForm').scroll_into_view_if_needed()
    page.screenshot(path=str(R/'qa/v093-camera-only-preview-mobile.png'))
    page.locator('#applyMicOnly').click()
    page.wait_for_function("document.querySelector('#mediaDeviceStatus').textContent.includes('MICROPHONE FAILED')")
    check('audio failure does not drop camera preview',page.evaluate('RetroApp.status.mode==="preview"'))
    check('audio request does NOT request camera',page.evaluate('__fx.constraints.at(-1).video===false'))
    check('camera track is STILL LIVE after mic failure',page.evaluate('__fx.streams.find(x=>x.stream.getVideoTracks().length>0).stream.getVideoTracks()[0].readyState==="live"'))
    check('mic error kept as its own diagnostic stage',page.evaluate('document.querySelector("#diagnosticRecent").textContent.includes("microphone_apply_failure")'))
    page.evaluate('RetroApp.go("booth")')
    check('guest Start disabled in camera-only preview',page.locator('#touchBtn').is_disabled())
    page.evaluate('RetroApp.start("touch")');page.wait_for_timeout(200)
    check('programmatic Start also fails closed in preview',page.evaluate('RetroApp.status.state==="idle"&&RetroApp.status.clipCount===0'))
    page.evaluate('RetroApp.go("admin")')
    with page.expect_download(timeout=12000) as download_ctx:page.locator('#diagExport').click()
    diagnostic=json.loads(Path(download_ctx.value.path()).read_text())
    check('export reports camera ready and mic unavailable',diagnostic['media']['cameraReady'] and not diagnostic['media']['microphoneReady'])
    check('export preserves specific failed audio stage',diagnostic['media']['lastFailure']['stage']=='apply_microphone_only')
    check('export contains independent microphone error event',any(e['name']=='microphone_apply_failure' for e in diagnostic['events']))
    videoBefore=page.evaluate('__fx.constraints.filter(c=>c.video!==false).length')
    page.locator('#applyDevices').click()
    page.wait_for_function("document.querySelector('#mediaDeviceStatus').textContent.includes('MICROPHONE FAILED')")
    check('sequential recovery preserves existing camera when mic fails',page.evaluate('(n)=>RetroApp.status.mode==="preview"&&__fx.constraints.filter(c=>c.video!==false).length===n',videoBefore))
    # Re-apply microphone without re-requesting or resetting the live video track.
    before=page.evaluate('__fx.constraints.filter(c=>c.video!==false).length')
    page.evaluate('window.__fx.failMic=false')
    page.locator('#applyMicOnly').click()
    page.wait_for_function('RetroApp.status.mode==="real"')
    check('mic can be attached later',page.evaluate('RetroApp.status.mode==="real"'))
    check('adding microphone does not reopen video',page.evaluate('(n)=>__fx.constraints.filter(c=>c.video!==false).length===n',before))
    check('mic meter has a synthetic source',page.locator('#micMeter').evaluate('node=>node.value>0'))
    page.locator('#releaseMicOnly').click()
    page.wait_for_function('RetroApp.status.mode==="preview"')
    check('releasing mic keeps camera active',page.evaluate('RetroApp.status.mode==="preview"'))
    check('guest Start remains locked after mic release',page.evaluate('document.querySelector("#touchBtn").disabled'))
    page.locator('#applyMicOnly').click()
    page.wait_for_function('RetroApp.status.mode==="real"')
    page.evaluate('RetroApp.go("booth")')
    check('both inputs unlock Start',not page.locator('#touchBtn').is_disabled())
    page.locator('#touchBtn').click()
    page.wait_for_function('RetroApp.status.state==="recording"',timeout=12000)
    check('recording follows two independent input streams',page.evaluate('RetroApp.status.mode==="real"&&RetroApp.status.state==="recording"'))
    page.wait_for_function('RetroApp.status.state==="idle"',timeout=35000)
    clip=page.evaluate('RetroApp.clips.at(-1)')
    check('clip is real and encoded',clip['kind']=='real' and clip['sizeBytes']>1000)
    check('recording was fixed ten seconds',10000<=clip['durationMs']<16000)
    page.evaluate('RetroApp.go("admin")')
    page.locator('#stopMediaInputs').click()
    page.wait_for_function('RetroApp.status.mode==="demo"')
    check('stop both releases media tracks',page.evaluate('__fx.streams.every(x=>x.stream.getTracks().every(t=>t.readyState==="ended"))'))
    check('no runtime JavaScript errors',not errors)
    # Mic-only path (with no camera): Start remains disabled.
    page.locator('#applyMicOnly').click();page.wait_for_function("document.querySelector('#mediaDeviceStatus').textContent.includes('MICROPHONE LIVE')")
    check('mic-only does not claim camera live',page.evaluate('RetroApp.status.mode==="demo"'))
    check('mic-only Start disabled',page.locator('#touchBtn').is_disabled())
    page.locator('#applyCameraOnly').click();page.wait_for_function('RetroApp.status.mode==="real"')
    check('camera can join mic without reacquiring audio',page.evaluate('RetroApp.status.mode==="real"'))
    page.locator('#stopMediaInputs').click();page.wait_for_function('RetroApp.status.mode==="demo"')
    page.set_viewport_size({'width':1920,'height':1080});page.wait_for_timeout(120)
    check('admin layout without overflow at landscape',page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'))
    (R/'qa/v093-camera-separation.json').write_text(json.dumps({'count':len(checks),'checks':checks,'errors':errors,'scope':'Mocked getUserMedia and BrowserStore, synthetic Canvas/oscillator; Android hardware not validated'},indent=2)+'\n')
    browser.close()
print('TOTAL',len(checks),'PASSED',flush=True)
